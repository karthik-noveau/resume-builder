/** Every icon a user may assign to a section. */
export const SELECTABLE_ICONS: IconName[] = ICON_LIBRARY.flatMap((g) => g.icons)

export function isSelectableIcon(name: string): name is IconName {
  return (SELECTABLE_ICONS as string[]).includes(name)
}

export { CONTACT_ICONS }

/**
 * Storage key for a section's icon override. Custom sections are keyed by id
 * so two of them ("Languages", "Volunteering") can carry different icons.
 */
export function sectionIconKey(sectionType: SectionType, customSectionId?: string): string {
  return sectionType === 'custom' && customSectionId ? `custom:${customSectionId}` : sectionType
}

/**
 * The icon a template should draw for a section: the user's override when set,
 * otherwise the template's own default. Every template resolves through this so
 * the override behaves identically across all of them.
 */
export function resolveSectionIcon(
  resume: Pick<Resume, 'sectionIcons'>,
  sectionType: SectionType,
  fallback: IconName,
  customSectionId?: string
): IconName {
  const chosen = resume.sectionIcons?.[sectionIconKey(sectionType, customSectionId)]
  return chosen && isSelectableIcon(chosen) ? chosen : fallback
}
