import { test, expect, type Page } from '@playwright/test'
import { createResume } from '../utils/flows'

async function createPopulatedEditor(page: Page, template?: string) {
  await createResume(page, template)
  for (const label of ['Personal details', 'Summary', 'Work experience', 'Education']) {
    await expect(page.getByRole('heading', { name: label, exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Fill with example', exact: true }).click()
    await page.getByRole('button', { name: 'Next', exact: true }).click()
  }
  await page.getByRole('button', { name: 'Full Editor', exact: true }).click()
  await expect(page).toHaveURL(/\/editor\/[^/]+$/)
}

test('canvas selects exact fields, keeps the page still, and offers a clean preview', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await createPopulatedEditor(page)
  const canvas = page.getByLabel('Resume canvas', { exact: true })
  const panel = page.getByLabel('Properties panel')
  const company = canvas.getByRole('button', { name: 'Edit company', exact: true }).nth(1)
  await company.scrollIntoViewIfNeeded()
  const scroll = await canvas.evaluate(el => el.scrollTop)
  await company.click()
  await expect(panel.getByRole('textbox', { name: 'Company', exact: true }).nth(1)).toBeFocused()
  expect(await canvas.evaluate(el => el.scrollTop)).toBeCloseTo(scroll, 0)
  await expect(canvas.locator('[data-canvas-selected]')).toHaveCount(1)
  await panel.getByRole('textbox', { name: 'Company', exact: true }).nth(1).fill('Canvas Example Labs')
  await panel.getByRole('textbox', { name: 'Company', exact: true }).nth(1).blur()
  await expect(company).toHaveText('Canvas Example Labs')

  const toolbar = page.getByRole('toolbar', { name: 'Canvas editing controls' })
  await expect(toolbar.getByRole('button')).toHaveCount(1)
  await expect(page.getByRole('note', { name: 'Canvas editing tip' })).toBeVisible()
  const toolbarBox = (await toolbar.boundingBox())!
  const labelBox = (await toolbar.getByText('Company', { exact: true }).boundingBox())!
  expect(labelBox.x).toBeGreaterThan(toolbarBox.x + toolbarBox.width / 2)
  await panel.getByRole('tab', { name: 'Design', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Design', exact: true })).toHaveAttribute('aria-selected', 'true')
  await company.click()
  await expect(page.getByRole('tab', { name: 'Design', exact: true })).toHaveAttribute('aria-selected', 'true')
  await panel.getByRole('tab', { name: 'Content', exact: true }).click()
  await expect(panel.getByRole('textbox', { name: 'Company', exact: true }).nth(1)).toBeFocused()

  await canvas.getByRole('button', { name: 'Edit description item', exact: true }).nth(1).click()
  await expect(panel.getByRole('textbox', { name: 'Achievements / bullet points item 2' }).first()).toBeFocused()
  await page.mouse.move(0, 0)
  await page.screenshot({ path: testInfo.outputPath('canvas-inspector.png') })

  const preview = page.getByRole('button', { name: 'Clean preview', exact: true })
  await preview.click()
  await expect(preview).toHaveAttribute('aria-pressed', 'true')
  await expect(canvas.locator('[data-canvas-selected]')).toHaveCount(0)
  await expect(canvas.getByRole('button')).toHaveCount(0)
  await expect(page.locator('[data-canvas-element-label]')).toHaveCount(0)
  await expect(canvas.getByText('Canvas Example Labs', { exact: true })).toBeVisible()
  await preview.click()
  await expect(canvas.locator('[data-canvas-selected]')).toHaveCount(1)

  await company.dblclick()
  const inline = canvas.locator('[contenteditable="true"]')
  await expect(inline).toBeFocused()
  await inline.fill('Inline Example Labs')
  await inline.press('Enter')
  await expect(company).toHaveText('Inline Example Labs')
  await expect(panel.getByRole('textbox', { name: 'Company', exact: true }).nth(1)).toHaveValue('Inline Example Labs')
  await expect(page.getByText('Saved', { exact: true })).toBeVisible()
  await page.reload()
  await expect(canvas.getByRole('button', { name: 'Edit company', exact: true }).nth(1)).toHaveText('Inline Example Labs')
})

