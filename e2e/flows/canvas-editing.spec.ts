test('contact labels stay beside their fields on a wide canvas', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1920, height: 1000 })
  await createPopulatedEditor(page, 'Clarity')
  const canvas = page.getByLabel('Resume canvas', { exact: true })
  await canvas.getByRole('button', { name: 'Edit website', exact: true }).click()
  const phone = canvas.getByRole('button', { name: 'Edit phone', exact: true })
  await phone.hover()
  const label = page.locator('[data-canvas-element-label]')
  await expect(label).toHaveText('Phone')
  await expect(label).toBeVisible()
  // Hover labels describe the pointer target; toolbar actions still describe
  // the selected field they will actually edit.
  await expect(page.getByRole('toolbar', { name: 'Canvas editing controls' }).getByText('Website', { exact: true })).toBeVisible()
  const field = (await phone.boundingBox())!
  const badge = (await label.boundingBox())!
  const dx = Math.max(field.x - badge.x - badge.width, badge.x - field.x - field.width, 0)
  const dy = Math.max(field.y - badge.y - badge.height, badge.y - field.y - field.height, 0)
  expect(Math.hypot(dx, dy)).toBeLessThanOrEqual(12)
  expect(badge.x + badge.width).toBeGreaterThan(field.x)
  expect(badge.x).toBeLessThan(field.x + field.width)
  await expect(canvas.locator('[title]')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('phone-label.png') })
})
