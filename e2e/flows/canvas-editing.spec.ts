test('canvas divider controls change the line, persist, and reset without shifting content', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await createPopulatedEditor(page, 'Clarity')
  const canvas = page.getByLabel('Resume canvas', { exact: true })
  const panel = page.getByLabel('Properties panel')
  const line = canvas.locator('[data-canvas-decoration="divider"]').first()
  const hitTarget = line.getByRole('button', { name: 'Edit divider line' })
  const original = await line.boundingBox()
  const summary = canvas.getByRole('button', { name: 'Edit summary', exact: true })
  await summary.click()
  const summaryY = (await summary.boundingBox())!.y
  expect((await hitTarget.boundingBox())!.height).toBeGreaterThanOrEqual(13.9)
  // Click beyond the painted stroke, inside its more forgiving hit area.
  await hitTarget.click({ position: { x: 30, y: 2 } })
  await expect(page.getByRole('tab', { name: 'Design', exact: true })).toHaveAttribute('aria-selected', 'true')
  const thickness = panel.getByRole('spinbutton', { name: 'Thickness (pt)' })
  const length = panel.getByRole('spinbutton', { name: 'Length (%)' })
  await expect(thickness).toBeVisible()
  await thickness.fill('3')
  await thickness.press('Enter')
  await length.fill('60')
  await length.press('Enter')
  await panel.getByRole('button', { name: 'Centre line', exact: true }).click()
  await panel.getByLabel('Line colour', { exact: true }).click()
  await page.locator('.ant-color-picker-hex-input input').fill('208475')
  await page.locator('.ant-color-picker-hex-input input').press('Enter')
  await panel.getByLabel('Line colour', { exact: true }).click()
  await expect(line.locator('[aria-hidden="true"]').last()).toHaveCSS('background-color', 'rgb(32, 132, 117)')
  const changed = await line.boundingBox()
  expect(changed!.width).toBeCloseTo(original!.width * 0.6, 0)
  expect(changed!.x).toBeCloseTo(original!.x + original!.width * 0.2, 0)
  expect(changed!.height).toBeGreaterThan(original!.height)
  expect((await summary.boundingBox())!.y).toBeCloseTo(summaryY, 0)
  await page.mouse.move(0, 0)
  await page.screenshot({ path: testInfo.outputPath('divider-controls.png') })
  await expect(page.getByText('Saved', { exact: true })).toBeVisible()
  await page.reload()
  await hitTarget.click()
  await expect(thickness).toHaveValue('3')
  await expect(length).toHaveValue('60')
  await expect(line.locator('[aria-hidden="true"]').last()).toHaveCSS('background-color', 'rgb(32, 132, 117)')
  await panel.getByRole('button', { name: 'Reset styling', exact: true }).click()
  await expect(length).toHaveValue('100')
  const restored = await line.boundingBox()
  expect(restored!.width).toBeCloseTo(original!.width, 0)
  expect(restored!.height).toBeCloseTo(original!.height, 0)
  // Section rules use the same controls, even when Content was selected.
  await page.getByRole('tab', { name: 'Content', exact: true }).click()
  await canvas.getByRole('button', { name: 'Edit divider line' }).nth(2).click()
  await expect(thickness).toBeVisible()
  await expect(canvas.locator('[data-canvas-selected]')).toHaveCount(1)
  const selectedLine = canvas.locator('[data-canvas-decoration="divider"][data-canvas-selected]')
  await expect(selectedLine).toHaveCSS('outline-offset', '0px')
  await expect(selectedLine).toHaveCSS('border-radius', '0px')
  await page.mouse.move(0, 0)
  const label = page.locator('[data-canvas-element-label]')
  await expect(label).toBeVisible()
  await expect(label).toHaveText('Divider line')
  const heading = await canvas.getByRole('button', { name: 'Edit experience section title', exact: true }).evaluate((element) => {
    const range = document.createRange()
    range.selectNodeContents(element)
    return range.getBoundingClientRect().toJSON()
  })
  const badge = (await label.boundingBox())!
  expect(badge.x >= heading.right || badge.x + badge.width <= heading.left
    || badge.y >= heading.bottom || badge.y + badge.height <= heading.top).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('divider-selection.png') })
  await canvas.getByRole('button', { name: 'Edit fullName', exact: true }).hover()
  await expect(label).toHaveText('Full name')
  await expect(label).toBeVisible()
  await canvas.getByRole('button', { name: 'Open profile photo in Personal Info', exact: true }).hover()
  await expect(label).toHaveText('Photo')
  await expect(label).toBeVisible()
  await page.mouse.move(0, 0)
  await expect(label).toHaveText('Divider line')
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect(label).toBeVisible()
  const area = (await canvas.boundingBox())!
  const zoomedBadge = (await label.boundingBox())!
  expect(zoomedBadge.x).toBeGreaterThanOrEqual(area.x)
  expect(zoomedBadge.x + zoomedBadge.width).toBeLessThanOrEqual(area.x + area.width)
})

